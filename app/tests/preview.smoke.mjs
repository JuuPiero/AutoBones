// Loop preview panel: appears for a clip, counts loops, scrubs to the seam, changes speed. Browser mode (Vite on :1420).
import { chromium } from "playwright-core";
let failed = 0; const check = (n, ok, d = "") => { console.log(`${ok ? "PASS" : "FAIL"}  ${n} ${d}`); if (!ok) failed++; };
const b = await chromium.launch({ channel: "msedge", headless: true, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const p = await b.newPage({ viewport: { width: 1360, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("http://localhost:1420"); await p.waitForSelector("canvas");
await p.setInputFiles("input[type=file]", process.argv[2]);
await p.waitForFunction(() => window.__viewer.getClips().length === 1, null, { timeout: 120000 });
await p.evaluate(() => document.querySelector(".step:nth-of-type(4)")?.scrollIntoView());
await p.locator("button", { hasText: "Phát" }).click();
await p.waitForSelector(".preview", { timeout: 5000 });
check("preview panel appears when a clip plays", true);
await p.locator(".preview button", { hasText: "2×" }).click();
check("speed 2x applied", (await p.evaluate(() => window.__viewer.getPlayback().speed)) === 2);
const t0 = await p.evaluate(() => window.__viewer.getPlayback());
await p.waitForFunction(() => window.__viewer.getPlayback().loops >= 1, null, { timeout: 20000 });
check("loop counter increments after the clip wraps", /Vòng [2-9]/.test(await p.locator(".preview").innerText()), `clip ${t0.duration.toFixed(1)}s at 2x`);
await p.locator(".preview button", { hasText: "Tới điểm nối" }).click();
await p.waitForTimeout(150);
const near = await p.evaluate(() => window.__viewer.getPlayback());
check("'to seam' jumps to the last 0.3s of the clip", near.time > near.duration - 0.8, `t=${near.time.toFixed(2)}/${near.duration.toFixed(2)}`);
await p.locator(".preview button", { hasText: "⏸" }).first().click();
const frozen1 = await p.evaluate(() => window.__viewer.getPlayback().time); await p.waitForTimeout(400);
check("pause freezes the clip", Math.abs((await p.evaluate(() => window.__viewer.getPlayback().time)) - frozen1) < 1e-3);
await p.evaluate(() => window.__viewer.seekClip(0.5));
check("scrubbing sets the time", Math.abs((await p.evaluate(() => window.__viewer.getPlayback().time)) - 0.5) < 0.02);
await p.screenshot({ path: process.argv[3] });
check("no page errors", errs.length === 0, errs.slice(0, 2).join(" | "));
await b.close(); if (failed) process.exit(1); console.log("all passed");
